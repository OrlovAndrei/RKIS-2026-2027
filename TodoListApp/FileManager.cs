using System;   // Подключаем базовое пространство имён .NET (общие типы: int, string, исключения и т.д.)
using System.IO; // Подключаем классы для работы с файлами и папками (File, Directory и др.)

// Статический класс: нельзя создать экземпляр, все методы вызываются как FileManager.Метод()
public static class FileManager
{
    // Проверяет наличие папки и создаёт её при необходимости.
    // Метод принимает путь к папке и ничего не возвращает (void)
    public static void EnsureDataDirectory(string dirPath)
    {
        // Если папки по указанному пути ещё нет...
        if (!Directory.Exists(dirPath))
        {
            // ...создаём её (вместе с недостающими родительскими папками)
            Directory.CreateDirectory(dirPath);
        }
    }

    // Сохраняет данные пользователя в файл.
    // Принимает объект профиля и путь к файлу, куда нужно записать данные
    public static void SaveProfile(Profile profile, string filePath)
    {
        // Формируем строки с данными профиля.
        string[] lines =           // Массив строк: каждый элемент станет отдельной строкой файла
        {
            profile.FirstName,             // 1-я строка файла: имя
            profile.LastName,              // 2-я строка файла: фамилия
            profile.BirthYear.ToString()   // 3-я строка файла: год рождения, преобразованный из числа в текст
        };

        // Записываем данные в файл.
        // Каждый элемент массива записывается с новой строки; если файл существует, он перезаписывается
        File.WriteAllLines(filePath, lines);
    }

    // Загружает профиль пользователя из файла.
    // Принимает путь к файлу и возвращает готовый объект Profile
    public static Profile LoadProfile(string filePath)
    {
        // Проверяем наличие файла.
        if (!File.Exists(filePath))   // Если файла по указанному пути нет...
        {
            // ...выбрасываем исключение «файл не найден»
            throw new FileNotFoundException(
                "Файл профиля не найден.",   // Текст сообщения об ошибке
                filePath                     // Путь к файлу, который не удалось найти
            );
        }

        // Читаем все строки файла.
        // Результат — массив, где каждый элемент соответствует одной строке файла
        string[] lines = File.ReadAllLines(filePath);

        // Проверяем корректность количества строк.
        if (lines.Length < 3)   // Нужно минимум 3 строки: имя, фамилия, год рождения
        {
            // Если данных меньше, выбрасываем исключение «некорректные данные»
            throw new InvalidDataException(
                "Файл профиля содержит недостаточно данных."   // Текст сообщения об ошибке
            );
        }

        // Преобразуем год рождения в число.
        // TryParse пытается превратить строку в int; при успехе кладёт результат в birthYear
        if (!int.TryParse(lines[2], out int birthYear))   // Если преобразование не удалось...
        {
            // ...выбрасываем исключение: в третьей строке не число
            throw new InvalidDataException(
                "Некорректный год рождения в файле профиля."   // Текст сообщения об ошибке
            );
        }

        // Создаём профиль из загруженных данных.
        // Порядок аргументов: имя (строка 0), фамилия (строка 1), год рождения (число)
        return new Profile(lines[0], lines[1], birthYear);
    }
}