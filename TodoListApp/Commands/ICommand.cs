// Общий контракт для всех команд: парсер создаёт команду, а главный цикл просто вызывает Execute()
public interface ICommand
{
    void Execute();

    // Отменить действие команды. У команд, которые ничего не меняют (view, help, read...),
    // отменять нечего, поэтому у метода есть реализация по умолчанию и такие команды её не пишут
    void Unexecute() { }
}
