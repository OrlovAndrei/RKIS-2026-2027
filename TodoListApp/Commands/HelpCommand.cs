public class HelpCommand : ICommand
{
    public void Execute()
    {
        Console.WriteLine(
            "help                       - список команд\n" +
            "profile                    - данные пользователя\n" +
            "add \"текст\"                - добавить задачу\n" +
            "add --multiline (-m)       - добавить многострочную задачу, ввод завершается строкой !end\n" +
            "view [флаги]               - показать задачи таблицей (по умолчанию только текст)\n" +
            "    --index (-i)           - показать номер задачи\n" +
            "    --status (-s)          - показать статус\n" +
            "    --update-date (-d)     - показать дату изменения\n" +
            "    --all (-a)             - показать всё; короткие флаги можно объединять: view -is\n" +
            "read <номер>               - полный текст задачи, статус и дата изменения\n" +
            "done <номер>               - отметить задачу выполненной\n" +
            "update <номер> \"текст\"     - изменить текст задачи\n" +
            "remove <номер>             - удалить задачу\n" +
            "exit                       - выход");
    }
}
